#!/usr/bin/env python3
"""Re-generates the detail sections on solutions.html (one per solution, alternating) from tools/solutions_data.py.
Run after editing solutions_data.py:  python3 tools/build_solutions.py && python3 tools/build_solutions_listing.py"""
import os, sys, html, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..')) + os.sep
sys.path.insert(0, os.path.dirname(__file__))
import solutions_data as D
E = lambda t: html.escape(str(t), quote=True)
ORDER = ['smart-water-meter', 'smart-electric-meter', 'smart-gas-meter', 'smart-street-light', 'transformer-monitoring']
SECTIONS = {'smart-water-meter': 'sl-water', 'smart-electric-meter': 'sl-electric', 'smart-gas-meter': 'sl-gas', 'smart-street-light': 'sl-street', 'transformer-monitoring': 'sl-dtms'}
CHECK = '<svg width="12" height="12" fill="none" stroke="currentColor" stroke-width="2.5" viewBox="0 0 24 24"><polyline points="20 6 9 17 4 12"/></svg>'
def root_rel(h): return h[3:] if h.startswith('../') else h
pages = {p['slug']: p for p in D.PAGES if p['dir'] == 'solutions'}
out = '<!-- SOLUTION DETAIL SECTIONS (generated by tools/build_solutions_listing.py) -->\n'
for i, slug in enumerate(ORDER):
    p = pages[slug]; ov = p['overview']; acc = p.get('accent', '#4f46e5'); href = f'solutions/{slug}.html'
    alt = i % 2 == 0
    stats = ''.join(f'<div class="sl-img-card__stat-item"><span class="sl-img-card__stat-num">{E(v)}</span><span class="sl-img-card__stat-label">{E(l)}</span></div>' for v, l in ov['stats'])
    metrics = ''.join(f'<div class="sl-metric"><span class="sl-metric__val">{E(v)}</span><span class="sl-metric__label">{E(l)}</span></div>' for v, l in ov['metrics'])
    feats = ''.join(f'<li><div class="sl-feat-list__icon" style="background:rgba(79,70,229,.1);color:{acc};">{CHECK}</div><span><strong>{E(a)}</strong> — {E(b)}</span></li>' for a, b in ov['features'][:5])
    chips = ''.join(f'<a href="{E(root_rel(h))}" class="sl-product-chip">{E(l)}</a>' for l, h in ov.get('chips', []))
    img = f'''<div class="col-lg-6 {'order-lg-2' if i % 2 else ''}" data-sl="{'right' if i % 2 else 'left'}">
        <div class="sl-img-card"><a href="{href}" aria-label="{E(ov['title'])}"><img src="assets/images/solutions/{ov['img']}" alt="{E(ov['alt'])}" loading="lazy"/></a>
          <div class="sl-img-card__stat">{stats}</div>
        </div>
      </div>'''
    txt = f'''<div class="col-lg-6 {'order-lg-1' if i % 2 else ''}" data-sl="{'left' if i % 2 else 'right'}">
        <span class="sl-solution__tag" style="background:rgba(79,70,229,.1);color:{acc};">{E(ov['tag'])}</span>
        <h2 class="sl-solution__title" style="color:#111827;">{E(ov['title'])}</h2>
        {''.join(f'<p class="sl-solution__desc" style="color:#374151;">{E(t)}</p>' for t in ov['desc'])}
        <div class="sl-metrics">{metrics}</div>
        <ul class="sl-feat-list">{feats}</ul>
        <div class="sl-products-strip">{chips}</div>
        <div style="display:flex;gap:.75rem;margin-top:1.75rem;flex-wrap:wrap;">
          <a href="{href}" class="sl-sol-btn sl-sol-btn--primary">View Details →</a>
          <a href="contact.html" class="sl-sol-btn sl-sol-btn--outline">Request Demo</a>
        </div>
      </div>'''
    out += f'''<section class="sl-solution{' sl-solution--alt' if alt else ''}" id="{SECTIONS[slug]}">
  <div class="container">
    <div class="row align-items-center g-5">
      {img}
      {txt}
    </div>
  </div>
</section>

'''
f = ROOT + 'solutions.html'; s = open(f, encoding='utf-8').read()
s = re.sub(r'<!-- SOLUTION DETAIL SECTIONS.*?(?=<section class="sl-section sl-section--surf">)', '', s, flags=re.S)
m = '<section class="sl-section sl-section--surf">'
assert s.count(m) == 1
s = s.replace(m, out + m)
open(f, 'w', encoding='utf-8').write(s); print('solutions.html detail sections:', len(ORDER))
