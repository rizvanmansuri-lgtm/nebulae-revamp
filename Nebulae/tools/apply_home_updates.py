#!/usr/bin/env python3
"""Home page data refresh (idempotent). Run from project root after build_pages.py / build_events.py:
   python3 tools/apply_home_updates.py [index.html index1.html ...]
 1. Protocol Comparison 'Our Products' row  <- tools/products_index.json (live counts, links without a wrong type filter)
 2. 'Events' section (between Updates and Case Studies) <- tools/events_data.json (upcoming first, then latest past)"""
import json, re, sys, os, datetime, html
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files=sys.argv[1:] or ['index.html','index1.html']
P=json.load(open(ROOT+'/tools/products_index.json',encoding='utf-8'))
EV=json.load(open(ROOT+'/tools/events_data.json',encoding='utf-8'))
cnt=lambda k:sum(1 for p in P if p['proto_key']==k)
cols=[('lora','lora',f'{cnt("lora")} products →'),('wisun','wisun',f'{cnt("wisun")} products →'),('zigbee','zigbee',f'{cnt("zigbee")} products →'),
      ('wifi','wifi',f'{cnt("wifi")} product →' if cnt('wifi')==1 else f'{cnt("wifi")} products →'),
      ('gsm','gsm',f'{cnt("gsm")} gateways →'),('ble','zigbee',f'{cnt("zigbee")} combo modules →')]
row='<tr class="nbl-compare-row--products">\n              <td class="nbl-compare-spec">Our Products</td>\n'+''.join(
  f'              <td><a href="products.html?proto={link}" class="nbl-proto-link nbl-proto-link--{cls}">{label}</a></td>\n' for cls,link,label in cols)+'            </tr>'
def card(e):
    past=e.get('isPast'); e_=html.escape
    badge='Past' if past else 'Upcoming'
    return f'''<div class="col-md-6 col-lg-4" data-anim="slide-up"><a class="hm-ev-card" href="event-{e['slug']}.html">
<span class="hm-ev-card__img"><img src="assets/images/events/{os.path.basename(e['image'])}" alt="{e_(e['name'])}" loading="lazy" width="540" height="390"><span class="hm-ev-card__badge hm-ev-card__badge--{'past' if past else 'up'}">{badge}</span></span>
<span class="hm-ev-card__body"><span class="hm-ev-card__tag">{e_(e.get('type','Event'))}</span><strong class="hm-ev-card__title">{e_(e['name'])}</strong>
<span class="hm-ev-card__meta">📅 {e_(e['date'])}</span><span class="hm-ev-card__meta">📍 {e_(e['location'])}</span>
<span class="hm-ev-card__link">{'Meet Us' if not past else 'View Details'} →</span></span></a></div>'''
up=sorted([e for e in EV if not e.get('isPast')],key=lambda e:e['iso']); past=sorted([e for e in EV if e.get('isPast')],key=lambda e:e['iso'],reverse=True)
sel=(up+past)[:3]
sec=f'''<!-- HOME-EVENTS:start (generated by tools/apply_home_updates.py) -->
<section class="hm-events-section" id="events">
  <div class="container">
    <div class="nbl-section-header nbl-section-header--center" data-anim="slide-up">
      <span class="nbl-section-eyebrow">Events</span>
      <h2 class="nbl-section-title">Meet Nebulae at Industry Events</h2>
      <p class="nbl-section-desc">Catch our team at exhibitions and conferences across India — see live demos of our Wi-SUN, LoRaWAN and smart-metering solutions.</p>
    </div>
    <div class="row g-4 justify-content-center">
{chr(10).join(card(e) for e in sel)}
    </div>
    <div class="nbl-updates-cta" data-anim="slide-up"><a href="news-events.html">View All Events →</a></div>
  </div>
</section>
<!-- HOME-EVENTS:end -->
'''
for f in files:
    p=ROOT+'/'+f
    if not os.path.exists(p): continue
    s=open(p,encoding='utf-8').read()
    s,n=re.subn(r'<tr class="nbl-compare-row--products">.*?</tr>',lambda m:row,s,count=1,flags=re.S)
    s=re.sub(r'<!-- HOME-EVENTS:start.*?HOME-EVENTS:end -->\n?','',s,flags=re.S)
    k=s.find('<!-- ═══ CASE STUDY HIGHLIGHTS ═══ -->')
    assert k>0,'marker missing in '+f
    s=s[:k]+sec+'\n'+s[k:]
    open(p,'w',encoding='utf-8').write(s); print(f,'compare row',n,'events',len(sel))
